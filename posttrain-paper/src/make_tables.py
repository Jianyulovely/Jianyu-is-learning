"""Aggregate runs/evals/*.json into the tables the paper actually needs.

Every number is traceable to a file under runs/evals/ (trained methods) or
runs/sample/ (training-free baselines). Nothing is typed in by hand, which is
the point: Tables 1-3 of the paper must be regenerated from raw JSON, never
copy-pasted.

Two separate tables, on purpose:
  * trained methods (SFT / RFT / DPO) have a *budget axis* -- we control it;
  * training-free methods (prompt-only, self-consistency) have exactly one
    operating point each, whose x-coordinate is a *measured* cost. Putting them
    in the same fixed-column table would silently imply they have a budget
    sweep they do not have.

Usage:
    python src/make_tables.py
    python src/make_tables.py --latex
    python src/make_tables.py --per-seed
    python src/make_tables.py --evals-dir /tmp/x --test math500
"""
from __future__ import annotations

import argparse
import json
import statistics as st
from pathlib import Path

from common import RUNS, setup_stdout

EVALS = RUNS / "evals"
SAMPLE = RUNS / "sample"
TRAINED = ["sft", "rft", "dpo"]
FREE = ["prompt_only", "sc"]
DASH = "-"


def load_evals(evals_dir: Path) -> list[dict]:
    rows = []
    if not evals_dir.exists():
        return rows
    for p in sorted(evals_dir.glob("*.json")):
        try:
            m = json.loads(p.read_text(encoding="utf-8"))
        except json.JSONDecodeError:
            print(f"[warn] unreadable {p}")
            continue
        if "parsers" not in m:
            continue
        m["_file"] = p.name
        rows.append(m)
    return rows


def load_baselines(sample_dir: Path) -> tuple[dict, float]:
    """(derive_stats, sampling_gpu_hours) or ({}, 0.0)."""
    ds, meta = {}, {}
    if (sample_dir / "derive_stats.json").exists():
        ds = json.loads((sample_dir / "derive_stats.json").read_text(encoding="utf-8"))
    if (sample_dir / "meta.json").exists():
        meta = json.loads((sample_dir / "meta.json").read_text(encoding="utf-8"))
    return ds, float(meta.get("gpu_hours_total", 0.0) or 0.0)


def agg(rows: list[dict], test: str, parser: str, methods: list[str]):
    out: dict[str, dict[float, list[float]]] = {}
    for r in rows:
        if r.get("test") != test or r["method"] not in methods:
            continue
        acc = r["parsers"][parser]["accuracy"]
        out.setdefault(r["method"], {}).setdefault(float(r["budget"]), []).append(acc)
    return out


def cell(vals: list[float] | None) -> str:
    if not vals:
        return DASH
    if len(vals) == 1:
        return f"{vals[0]:.3f}"
    return f"{st.mean(vals):.3f} +/- {st.stdev(vals):.3f}"


def fmt_budget(hours: float) -> str:
    """Column label for the budget axis. The sweep is 5/15/30/60 minutes."""
    if 0 < hours < 1:
        return f"{round(hours * 60):g}m"
    return f"{hours:g}h"


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--test", default="gsm8k_test")
    ap.add_argument("--parser", default="standard")
    ap.add_argument("--latex", action="store_true")
    ap.add_argument("--per-seed", action="store_true")
    ap.add_argument("--evals-dir", default=None)
    ap.add_argument("--sample-dir", default=None)
    args = ap.parse_args()
    setup_stdout()

    evals_dir = Path(args.evals_dir) if args.evals_dir else EVALS
    sample_dir = Path(args.sample_dir) if args.sample_dir else SAMPLE

    rows = load_evals(evals_dir)
    if not rows:
        raise SystemExit(f"no eval JSON under {evals_dir}. Run src/eval_math.py first.")
    baselines, sample_hours = load_baselines(sample_dir)

    trained = agg(rows, args.test, args.parser, TRAINED)
    budgets = sorted({b for m in trained.values() for b in m})
    methods = [m for m in TRAINED if m in trained]

    if args.per_seed:
        print(f"\n## Per-seed accuracy ({args.test}, {args.parser})\n")
        print("| method | budget | per-seed accuracies |")
        print("|---|---|---|")
        for m in methods:
            for b in sorted(trained[m]):
                vals = trained[m][b]
                print(f"| {m} | {fmt_budget(b)} | " + ", ".join(f"{v:.3f}" for v in vals) + " |")
        return

    # ------------------------------------------------------- table 1: trained
    if args.latex:
        print("% auto-generated by src/make_tables.py --latex")
        print(r"\begin{tabular}{l" + "c" * len(budgets) + "}")
        print(r"\toprule")
        print(" & ".join(["Method"] + [fmt_budget(b) for b in budgets]) + r" \\")
        print(r"\midrule")
        for m in methods:
            print(" & ".join([m] + [cell(trained[m].get(b)) for b in budgets]) + r" \\")
        print(r"\bottomrule")
        print(r"\end{tabular}")
        return

    print(f"\n## Table 1 - trained methods, {args.test} accuracy ({args.parser} parser)\n")
    print("| method | " + " | ".join(fmt_budget(b) for b in budgets) + " |")
    print("|" + "---|" * (len(budgets) + 1))
    for m in methods:
        print("| " + m + " | " + " | ".join(cell(trained[m].get(b)) for b in budgets) + " |")

    # ------------------------------------- table 2: training-free, measured cost
    print(f"\n## Table 2 - training-free baselines ({args.test}, {args.parser} parser)\n")
    print("| method | measured GPU-hours | accuracy |")
    print("|---|---|---|")
    po = agg(rows, args.test, args.parser, ["prompt_only"])
    for m, per_b in po.items():
        vals = [v for vs in per_b.values() for v in vs]
        hours = {float(r["budget"]) for r in rows
                 if r["method"] == "prompt_only" and r.get("test") == args.test}
        h = min(hours) if hours else 0.0
        print(f"| prompt_only | {h:g} | {cell(vals)} |")

    if baselines:
        b = baselines.get("baselines", baselines)
        kk = baselines.get("k", "?")
        if args.parser in b:
            print(f"| self-consistency@{kk} | {sample_hours:.2f} "
                  f"| {b[args.parser]['vote_accuracy']:.3f} |")
        else:
            print(f"| self-consistency | {sample_hours:.2f} | {DASH} |")

    # ------------------------------------------------- table 3: format dividend
    print(f"\n## Table 3 - format dividend, lenient vs strict ({args.test})\n")
    print("| method | lenient | standard | strict | dividend | mean tokens |")
    print("|---|---|---|---|---|---|")
    seen: dict[str, dict] = {}
    for r in rows:
        if r.get("test") != args.test:
            continue
        p = r["parsers"]
        d = seen.setdefault(r["method"], {"lenient": [], "standard": [], "strict": [],
                                          "len": []})
        for k in ("lenient", "standard", "strict"):
            d[k].append(p[k]["accuracy"])
        d["len"].append(r.get("mean_output_tokens", 0))
    for m, d in seen.items():
        le, sa, sr = (st.mean(d[k]) for k in ("lenient", "standard", "strict"))
        print(f"| {m} | {le:.3f} | {sa:.3f} | {sr:.3f} | "
              f"{le - sr:+.3f} | {st.mean(d['len']):.0f} |")

    print("\n> Read from runs/evals/ and runs/sample/. "
          "A '-' means that run has not been executed yet.")


if __name__ == "__main__":
    main()
